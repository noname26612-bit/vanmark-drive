// Кто ведёт СПРАВОЧНИК КОЛЛЕКТИВА — вкладка «Команда» (PRD §18, решение Артёма 21.08.2026):
// карточки сотрудников, дни рождения и отпуска/отсутствия.
//
// Третий белый список прав рядом с двумя существующими (см. task-access.ts):
//
//   isTaskManagerRole  — заявки (ADMIN | DISPATCHER | SERVICE_MANAGER).
//   isDispatcherRole   — смены, KPI и нарушения, простой, сводка, расценка, админка (ADMIN | DISPATCHER).
//   isTeamManagerRole  — справочник коллектива: люди, дни рождения, отсутствия.
//
// Зачем отдельный список, если сегодня он роль в роль совпадает с isTaskManagerRole. До 21.08.2026
// «Команда» была прибита к диспетчерскому контуру (requireDispatcher), и Артём открыл правку
// менеджеру-сервиснику. Ослаблять ради этого isDispatcherRole нельзя — вместе с кадрами он отдал бы
// Максиму смены, KPI и деньги. Переиспользовать isTaskManagerRole тоже неправильно: кадры и заявки —
// разные вопросы, и когда появится роль, которая ведёт заявки, но не трогает коллектив (или
// наоборот), совмещённый список молча даст ей лишнее. Правило прежнее: новую роль вписывать в
// НУЖНЫЙ список явно, никогда не писать «роль не DRIVER ⇒ можно».
import type { Role } from "@/generated/prisma/enums";
import { Errors } from "./errors";

/** Роли, которые ведут справочник коллектива: диспетчер (Милена), админ, менеджер-сервисник (Максим). */
export function isTeamManagerRole(role: Role): boolean {
  return role === "ADMIN" || role === "DISPATCHER" || role === "SERVICE_MANAGER";
}

/** Гейт для доменных функций: не ведёт коллектив — 403 (существование коллег не секрет). */
export function assertTeamManager(actor: { role: Role }): void {
  if (!isTeamManagerRole(actor.role)) throw Errors.forbidden();
}
