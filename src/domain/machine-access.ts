// Доступ к разделам оборудования — «Листогибы» и «Фальцепрокатники» (ARCHITECTURE §4г/§6, PRD §16).
// ЕДИНСТВЕННЫЙ источник правды по тому, кто вообще имеет право работать с картотекой.
//
// Принцип — БЕЛЫЙ список ролей, никогда «все кроме водителя»: именно допущение «не DRIVER ⇒ штаб»
// пускает новую роль в чужие разделы.
//
// С 15.08.2026 к белому списку добавлен ПЕРСОНАЛЬНЫЙ флаг User.equipmentAccess: Артём открыл
// оборудование Николаю и Александру, оставив их водителями (задачи, смены и KPI считаются как
// раньше). Это единственное право в системе, выданное не ролью, поэтому:
//   • флаг расширяет доступ, но не отменяет ни одной проверки — водитель со флагом по-прежнему
//     не видит KPI, сводку, смены и админку (они закрыты своими белыми списками ролей);
//   • флаг читается ИЗ БД в guard'е (src/lib/api-route.ts, src/lib/session.ts), а не из JWT:
//     включение и отзыв действуют сразу, без перезахода пользователя.
//
// Изоляции «по владельцу» у модуля НЕТ by design: картотека площадки общая, все допущенные видят
// весь парк (в отличие от задач, где водитель видит только свои). Поэтому вся защита модуля —
// проверка допуска, и она обязана стоять в КАЖДОМ handler'е, включая раздачу фото.
import type { Role } from "@/generated/prisma/enums";
import { Errors } from "./errors";

/** Кого пускает роль: менеджер-сервисник, диспетчер (Милена), админ. */
export function isMachineRole(role: Role): boolean {
  return role === "SERVICE_MANAGER" || role === "DISPATCHER" || role === "ADMIN";
}

/** Актор модуля: роль из сессии + персональный флаг из БД (у ролевых пользователей не спрашивается). */
export type EquipmentActor = { role: Role; equipmentAccess?: boolean };

/** Допущен ли пользователь к оборудованию: роль из белого списка ИЛИ персональный флаг. */
export function canAccessEquipment(actor: EquipmentActor): boolean {
  return isMachineRole(actor.role) || actor.equipmentAccess === true;
}

/**
 * Гейт модуля для доменных функций. Недопущенному отдаём 404, а не 403: существование модуля не
 * раскрываем — та же логика, что с чужой задачей (§6).
 */
export function assertMachineAccess(actor: EquipmentActor): void {
  if (!canAccessEquipment(actor)) throw Errors.notFound();
}
