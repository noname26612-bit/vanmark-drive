// Доступ к модулю «Станки» (ARCHITECTURE §4г/§6, PRD §16). ЕДИНСТВЕННЫЙ источник правды по тому,
// кто вообще имеет право работать с картотекой. Роль берётся только из сессии.
//
// Принцип — БЕЛЫЙ список ролей, никогда «все кроме водителя»: именно допущение «не DRIVER ⇒ штаб»
// пускает новую роль в чужие разделы. Здесь и наоборот: водитель в модуль станков не попадает.
//
// Изоляции «по владельцу» у модуля НЕТ by design: картотека площадки общая, все трое видят весь
// парк (в отличие от задач, где водитель видит только свои). Поэтому вся защита модуля — ролевая,
// и она обязана стоять в КАЖДОМ handler'е, включая раздачу фото.
import type { Role } from "@/generated/prisma/enums";
import { Errors } from "./errors";

/** Роли с полным доступом к картотеке станков: менеджер-сервисник, диспетчер (Милена), админ. */
export function isMachineRole(role: Role): boolean {
  return role === "SERVICE_MANAGER" || role === "DISPATCHER" || role === "ADMIN";
}

/**
 * Гейт модуля для доменных функций. Водителю (и любой будущей роли вне белого списка) отдаём
 * 404, а не 403: существование модуля не раскрываем — та же логика, что с чужой задачей (§6).
 */
export function assertMachineAccess(actor: { role: Role }): void {
  if (!isMachineRole(actor.role)) throw Errors.notFound();
}
