-- Категория станка становится СПИСКОМ (решение Артёма 20.08.2026): «наш на продажу может быть и
-- арендным» — одна и та же машина стоит на площадке и под продажу, и под аренду, а карточка
-- заставляла выбрать что-то одно и потому врала.
--
-- Инварианты держит домен (src/domain/machine-status.ts), а не БД:
--   • список непустой;
--   • «Клиентский» ни с чем не совмещается — чужое железо остаётся чужим;
--   • схема номера выводится из наличия CLIENT: есть — «К-N», нет — «77-N».
-- Проверок на уровне Postgres не заводим: это правила предметной области, они меняются вместе с
-- продуктом, и место им там же, где остальные (то же решение, что по матрице состояний).
--
-- Колонка объявляется ровно так, как её видит Prisma для scalar list — без NOT NULL и без DEFAULT
-- (иначе следующий `migrate dev` увидит дрейф схемы и предложит «починить» рабочую базу).
--
-- Написано вручную (не `migrate diff`): генератор подкладывает паразитный
--     DROP SEQUENCE "machine_number_seq"/"task_number_seq"
-- и вдобавок DROP TABLE "machine_number_backup_20260815" — бэкап номеров от 15.08 живёт вне схемы
-- Prisma и должен дожить свой месяц.

-- AlterTable
ALTER TABLE "Machine" ADD COLUMN "categories" "MachineCategory"[];

-- ─────────────────────────── Перенос данных ───────────────────────────
-- Одиночная категория становится списком из одного элемента: смысл карточек не меняется,
-- совмещать категории люди начнут руками там, где это правда.
UPDATE "Machine" SET "categories" = ARRAY["category"];

-- Бэкап прежних значений — обычная таблица вне схемы Prisma, по образцу перенумерации 15.08.
-- Если что-то поедет, восстановить будет откуда, не поднимая дамп целиком.
-- Удалить отдельной миграцией, когда решение отстоится (ориентир — месяц).
CREATE TABLE IF NOT EXISTS "machine_category_backup_20260820" AS
SELECT id, "category", now() AS "backedUpAt"
FROM "Machine";

-- Подстраховка на случай пустого списка: карточка без категории сломала бы и номер, и фильтры.
-- Клиентской считать чужое железо нельзя, поэтому пустые (их быть не должно) уходят в «наш на продажу».
UPDATE "Machine"
SET "categories" = ARRAY['OUR_SALE']::"MachineCategory"[]
WHERE "categories" IS NULL OR cardinality("categories") = 0;

-- ─────────────────────────── Снос старой колонки ───────────────────────────
-- Индекс по одиночной категории больше не к чему приложить: список фильтруется через `has`,
-- а GIN-индекс на тридцати карточках дороже последовательного чтения.
DROP INDEX "Machine_category_status_idx";

ALTER TABLE "Machine" DROP COLUMN "category";
