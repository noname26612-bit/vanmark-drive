-- Состояние «Принят» выведено из оборота (решение Артёма 20.08.2026).
--
-- На площадке оно ничего не значило: станок приезжает уже с работой, и карточка сразу же
-- переводилась в «Требует ремонта». Лишний шаг путал Максима и раздувал ряд счётчиков.
-- Значение ACCEPTED из типа НЕ УДАЛЯЕМ: на него ссылается история MachineEvent (fromStatus/toStatus),
-- а удаление значения enum в Postgres требует пересоздания типа со всеми зависимостями.
-- Домен просто перестаёт его предлагать (SELECTABLE_MACHINE_STATUSES в src/domain/machine-status.ts).
--
-- Написано вручную (не `migrate diff`): генератор подкладывает паразитный
--     DROP SEQUENCE "machine_number_seq"/"task_number_seq"
-- — он снёс бы сквозную нумерацию станков и заявок на проде.

-- Всё, что стояло «Принят», становится «Требует ремонта» — ровно то, что люди делали руками.
UPDATE "Machine" SET "status" = 'NEEDS_REPAIR' WHERE "status" = 'ACCEPTED';

-- Новые карточки заводятся сразу в «Требует ремонта».
ALTER TABLE "Machine" ALTER COLUMN "status" SET DEFAULT 'NEEDS_REPAIR';
